import { VERSION } from '../version.js';
import type { AgentInventory, McpServerItem, ScanResult, Severity } from '../core/types.js';
import { mcpScope, mcpTarget, surfaceCounts } from './inventory-text.js';
import type { Reporter } from './reporter.js';
import { renderOwaspAgenticCoverageMarkdown } from './owasp-agentic.js';
import { renderOwaspMcpCoverageMarkdown } from './owasp-mcp.js';
import { escapeControlChars } from './text-safety.js';

/**
 * Text from scanned hosts on one Markdown line: no line breaks (a newline in a
 * cwd folder name would start a new heading), no raw HTML, no table breaks.
 */
function mdInline(s: string): string {
  return escapeControlChars(s.replace(/[\r\n\u2028\u2029]+/g, ' '))
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\|/g, '\\|');
}

const SEVERITY_EMOJI: Record<Severity, string> = {
  critical: 'x',
  warning: '!',
  info: 'i',
};

export class MarkdownReporter implements Reporter {
  readonly format = 'markdown';

  render(result: ScanResult): string {
    const lines: string[] = [];

    lines.push('# VASO Security Scan Report');
    lines.push('');
    lines.push(`**Date:** ${result.timestamp}`);
    lines.push(`**Score:** ${result.totalScore}/100 (${result.totalGrade})`);
    if (result.agents.length > 1) {
      // Headline score is worst-case (weakest agent); show the mean as context.
      lines.push(`**Fleet average:** ${result.fleetAverage}/100`);
    }
    lines.push(`**Agents scanned:** ${result.agents.length}`);
    lines.push('');

    lines.push('## Summary');
    lines.push('');
    lines.push(`| Severity | Count |`);
    lines.push(`|----------|-------|`);
    lines.push(`| Critical | ${result.summary.critical} |`);
    lines.push(`| Warning | ${result.summary.warning} |`);
    lines.push(`| Info | ${result.summary.info} |`);
    lines.push(`| Passed | ${result.summary.passed} |`);
    lines.push(`| **Total** | **${result.summary.total}** |`);
    lines.push('');

    for (const agent of result.agents) {
      const agentLabel = agent.installation.agentName
        ? `${mdInline(agent.agent)} (agent: ${mdInline(agent.installation.agentName)})`
        : mdInline(agent.agent);
      lines.push(`## ${agentLabel} (Score: ${agent.score}, Grade: ${agent.grade})`);
      lines.push('');

      const failed = agent.results.filter(r => !r.passed);
      const passed = agent.results.filter(r => r.passed);

      if (failed.length > 0) {
        lines.push('### Findings');
        lines.push('');
        lines.push('| ID | Name | Severity | Message |');
        lines.push('|----|------|----------|---------|');
        for (const r of failed) {
          lines.push(`| ${r.id} | ${r.name} | ${r.severity} | ${mdInline(r.message)} |`);
        }
        lines.push('');
      }

      if (passed.length > 0) {
        lines.push(`### Passed (${passed.length})`);
        lines.push('');
        for (const r of passed) {
          lines.push(`- **${r.id}**: ${r.name}`);
        }
        lines.push('');
      }

      if (agent.installation.inventory) lines.push(...renderSurface(agent.installation.inventory));
    }

    const host = result.hostInventory;
    if (host && (host.mcpServers.length > 0 || host.sharedMcpServers?.length)) {
      lines.push('## Host');
      lines.push('');
      if (host.sharedMcpServers?.length) {
        lines.push('### MCP servers shared by several agents');
        lines.push('');
        lines.push('An update or compromise of one reaches every agent listed; an unpinned one can change under all of them at once.');
        lines.push('');
        lines.push('| Server | Unpinned | Used by |');
        lines.push('|--------|----------|---------|');
        for (const g of host.sharedMcpServers) {
          const users = g.users.map(u => `${u.agent}${u.agentName ? ` (${u.agentName})` : ''}: ${u.server}`).join(', ');
          lines.push(`| ${cell(g.key)} | ${g.unpinned ? 'yes' : '—'} | ${cell(users)} |`);
        }
        lines.push('');
      }
      if (host.mcpServers.length > 0) {
        lines.push('### MCP servers no detected agent owns');
        lines.push('');
        lines.push('VS Code, a project mcp.json.');
        lines.push('');
        lines.push(...renderMcpTable(host.mcpServers));
      }
    }

    const owasp = renderOwaspMcpCoverageMarkdown(result);
    if (owasp) {
      lines.push(owasp);
    }

    const owaspAgentic = renderOwaspAgenticCoverageMarkdown(result);
    if (owaspAgentic) {
      lines.push(owaspAgentic);
    }

    lines.push('---');
    lines.push(`*Generated by VASO (VULNEX Agent Security Observer) ${(result.vasoVersion ?? VERSION).replace(/[^\w.+-]/g, '')}*`);

    return lines.join('\n');
  }
}

const cell = (s: string) => mdInline(s) || '—';

function renderSurface(inventory: AgentInventory): string[] {
  const lines = [`### Attack surface (${surfaceCounts(inventory)})`, ''];
  for (const dir of inventory.skillsDirs) {
    lines.push(`- Skills directory: \`${mdInline(dir.path)}\`${dir.exists ? '' : ' (not present)'}`);
  }
  if (inventory.skillsDirs.length > 0) lines.push('');
  if (inventory.skills.length > 0) {
    lines.push('| Skill | Description | Path | Files | Code | Findings |');
    lines.push('|-------|-------------|------|-------|------|----------|');
    for (const skill of inventory.skills) {
      const path = skill.symlinkTarget ? `${skill.path} → ${skill.symlinkTarget}` : skill.path;
      lines.push(`| ${cell(skill.name)} | ${cell(skill.description ?? '')} | ${cell(path)} | ${skill.files} | ${skill.hasCode ? 'yes' : '—'} | ${cell((skill.findings ?? []).join(', '))} |`);
    }
    lines.push('');
  }
  if (inventory.otherEntries.length > 0) {
    lines.push('Other entries (no SKILL.md):');
    lines.push('');
    for (const e of inventory.otherEntries) lines.push(`- \`${mdInline(e.path)}\` (${e.type}, ${e.files} file${e.files === 1 ? '' : 's'})`);
    lines.push('');
  }
  if (inventory.mcpServers?.length) lines.push(...renderMcpTable(inventory.mcpServers));
  for (const note of inventory.incomplete ?? []) lines.push(`> ! ${mdInline(note)}`, '');
  return lines;
}

function renderMcpTable(servers: McpServerItem[]): string[] {
  const lines = ['| MCP server | Transport | Runs / reaches | Scope | Env / headers | Config | Findings |'];
  lines.push('|------------|-----------|----------------|-------|---------------|--------|----------|');
  for (const s of servers) {
    const names = [...(s.envNames ?? []), ...(s.headerNames ?? [])].join(', ');
    lines.push(`| ${cell(s.name)} | ${s.transport} | ${cell(mcpTarget(s))} | ${cell(mcpScope(s))} | ${cell(names)} | ${cell(s.configFile)} | ${cell((s.findings ?? []).join(', '))} |`);
  }
  lines.push('');
  return lines;
}
