/**
 * npm packages deprecated in every version (npm registry, 2026-10-12): no
 * release will get a fix. Reported at info by MCP-027 when a server ships one
 * directly. Version-bound deprecations (multer 1.x) are covered by advisories.
 */
export const DEPRECATED_NPM_PACKAGES: Readonly<Record<string, string>> = {
  request: 'deprecated since 2020; use fetch, undici or axios',
  'request-promise': 'deprecated with request',
  'request-promise-native': 'deprecated with request',
  'node-uuid': 'deprecated; use uuid',
  'har-validator': 'no longer supported',
  inflight: 'unsupported and leaks memory; use lru-cache',
};

function lib(
  cve: string,
  ghsa: string,
  ecosystem: 'npm' | 'pypi',
  name: string,
  versionConstraint: string,
  fixedVersion: string | undefined,
  severity: Advisory['severity'],
  published: string,
  title: string,
  description: string,
): Advisory {
  return {
    id: cve,
    title,
    agent: 'mcp',
    affectedVersions: versionConstraint,
    ...(fixedVersion ? { fixedVersion } : {}),
    severity,
    description,
    reference: `https://github.com/advisories/${ghsa}`,
    published,
    tags: ['dependency', 'cve', ecosystem],
    affectedDependency: { name, versionConstraint, ...(ecosystem === 'pypi' ? { ecosystem } : {}) },
  };
}
